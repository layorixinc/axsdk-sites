#!/usr/bin/env node
// Generates the RPC site-data module by READING the site adapters, not by copying from them.
//
// Three migration slices in a row failed identically: the adapter already declared what the reader
// needed — blocked markers, then the paging shape, then the hydration payload — and the RPC site data
// had never received it. Every time the symptom was a plausible wrong answer (an empty store, a store
// that cannot page) rather than an error, and every time the fix was a hand-copied block.
//
// So nothing is selected here. The adapter's own config table is loaded, taken whole, and written out.
// A key that exists cannot be forgotten, and a key that appears later arrives with the next build.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadLuaModules } from './lua/harness.mjs';

export const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Storefronts served by the shared adapter. amazon and ebay carry bespoke layers and are not here. */
export const STOREFRONT_SITES = Object.freeze([
  '11st', 'aliexpress', 'coupang', 'etsy', 'gmarket', 'naver-shopping', 'ssg', 'walmart',
]);

/**
 * Loads the real common layer plus each site adapter and returns the config table each one registered.
 * Reading the registered table rather than parsing the file means the data is exactly what the runtime
 * would see, including defaults the adapter fills in itself.
 */
export function readSiteConfigs({ root = repoRoot, sites = STOREFRONT_SITES } = {}) {
  const common = readdirSync(join(root, '_common', 'scripts'))
    .filter((file) => file.endsWith('.lua')).sort()
    .map((file) => `_common/scripts/${file}`);
  const adapters = sites.map((site) => `${site}/scripts/00_common.lua`);

  const lua = loadLuaModules([...common, ...adapters]);
  try {
    lua.define('function __rpc_dump_configs() return AX_STOREFRONT.configs end');
    return lua.call('__rpc_dump_configs');
  } finally {
    lua.close();
  }
}

const KEYWORDS = new Set(['and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'goto',
  'if', 'in', 'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while']);

const luaString = (value) => `"${String(value)
  .replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}"`;

const luaKey = (key) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) && !KEYWORDS.has(key) ? key : `[${luaString(key)}]`);

function luaValue(value, path, indent) {
  if (value === null || value === undefined) return 'nil';
  if (typeof value === 'boolean' || typeof value === 'number') return String(value);
  if (typeof value === 'string') return luaString(value);
  if (typeof value === 'function') {
    // Silently dropping it would leave the reader behaving as if the site never declared it — the exact
    // failure this generator exists to end.
    throw new Error(`${path} is a function; the RPC site data cannot carry it`);
  }
  const pad = '  '.repeat(indent + 1);
  const close = '  '.repeat(indent);
  if (Array.isArray(value)) {
    if (value.length === 0) return '{}';
    const items = value.map((item, index) => `${pad}${luaValue(item, `${path}[${index + 1}]`, indent + 1)}`);
    return `{\n${items.join(',\n')}\n${close}}`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) return '{}';
  const body = entries.map(([key, item]) => `${pad}${luaKey(key)} = ${luaValue(item, `${path}.${key}`, indent + 1)}`);
  return `{\n${body.join(',\n')}\n${close}}`;
}

/** The generated module source: one `RPC_SITES[<site>]` assignment per adapter, in a stable order. */
export function serializeSites(configs) {
  const header = [
    '-- GENERATED by tools/build-rpc-sites.mjs — do not edit.',
    '--',
    '-- Every value here is the site adapter\'s own registered config, taken whole. Nothing is selected,',
    '-- so a key the adapter declares cannot be missing from the reader: three migration slices in a row',
    '-- were fixed by copying a block that had been left behind.',
    'RPC_SITES = {}',
    '',
  ];
  const blocks = Object.keys(configs).sort().map((site) =>
    `RPC_SITES[${luaString(site)}] = ${luaValue(configs[site], site, 0)}\n`);
  return `${header.join('\n')}${blocks.join('\n')}`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const target = process.argv[2] ?? '_common/scripts/62_rpc_sites.lua';
  const source = serializeSites(readSiteConfigs());
  writeFileSync(join(repoRoot, target), source);
  const bytes = Buffer.byteLength(source, 'utf8');
  console.log(`wrote ${target} — ${STOREFRONT_SITES.length} sites, ${(bytes / 1024).toFixed(1)} KiB`);
  if (bytes > 48 * 1024) console.log(`  over the 48 KiB module discipline (limit 64 KiB)`);
}
